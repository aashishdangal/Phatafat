/**
 * Builds src/data/dictionary.json, the free-typing dictionary.
 *
 *   node scripts/build-dictionary.mjs
 *
 * Inputs, in priority order (earlier words win ties when free mode has to
 * pick which word to display):
 *   1. src/data/words.json      — Phatafat's own common words
 *   2. src/data/passages.json   — every word of every passage
 *   3. data/vendor/tesseract-nep/nep.wordlist (Apache 2.0) — ~30k words,
 *      roughly in frequency order
 *
 * Only pure Devanagari words are kept (trailing danda and commas stripped,
 * ZWJ/ZWNJ kept so eyelash ra survives). No network, no dependencies.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

const WORD = /^[ऀ-ॿ‌‍]+$/;
const DIGITS = /[०-९]/;

function clean(raw) {
  const word = raw.normalize("NFC").trim().replace(/[।॥,.!?;:]+$/u, "");
  if (!WORD.test(word) || DIGITS.test(word)) return null;
  // A lone sign or matra is not a word.
  if (!/[अ-हक़-ॡ]/.test(word)) return null;
  return word;
}

const ours = JSON.parse(read("src/data/words.json")).common;
const passageWords = JSON.parse(read("src/data/passages.json")).passages.flatMap((p) =>
  p.text.trim().split(/\s+/),
);
const vendor = read("data/vendor/tesseract-nep/nep.wordlist").split(/\r?\n/);

const seen = new Set();
const words = [];
for (const raw of [...ours, ...passageWords, ...vendor]) {
  const word = clean(raw);
  if (word === null || seen.has(word)) continue;
  seen.add(word);
  words.push(word);
}

const out = {
  _comment:
    "Generated by scripts/build-dictionary.mjs. Do not edit by hand. Includes the Tesseract OCR Nepali word list (Apache 2.0, see data/vendor/tesseract-nep).",
  words,
};
fs.writeFileSync(path.join(root, "src/data/dictionary.json"), JSON.stringify(out) + "\n");
console.log(`dictionary.json: ${words.length} words`);
